// Record<Key, Entry>, so a key missing there (or one that exists only there)
// is a compile error.
//
// Syntax, for every language:
// - {name} is a parameter. Parameters are escaped when rendered (they may hold
//   report text); a parameter that is itself html`` output is inserted as is.
// - [b]…[/b], [code]…[/code] and [kbd]…[/kbd] are the only markup a
//   translation can carry. Everything else in a translation is escaped, so a
//   translation cannot add tags, attributes or links.
// - An entry can be {one, other}: chosen with Intl.PluralRules on the {n}
//   parameter. English uses one/other; Chinese and Vietnamese have no plural
//   forms and use plain strings.

export type Plural = { one?: string; other: string };
